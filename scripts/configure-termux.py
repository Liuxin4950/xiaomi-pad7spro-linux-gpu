"""Configure an existing Debian GPU rootfs from a fresh Termux; files only, no session restart."""
import argparse
import base64
import hashlib
import json
import os
from pathlib import Path
import re
import shlex
import stat
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
ENTRIES = {
    'debian-shell.sh': 'debian-shell.sh',
    'debian-root.sh': 'debian-root.sh',
    'debian-stop.sh': 'debian-stop.sh',
    'debian-desktop.sh': 'debian-desktop.sh',
    'mali-work/desktop-zink.sh': 'desktop-zink.sh',
    '.shortcuts/debian-zink.sh': 'debian-zink-widget.sh',
}
REQUIRED = ('bash', 'adb', 'termux-x11', 'pulseaudio', 'pactl', 'pgrep', 'realpath', 'flock', 'nohup')


def digest(data):
    return hashlib.sha256(data).hexdigest()


def safe_path(value):
    path = Path(value)
    if not re.fullmatch(r'/[A-Za-z0-9_.@%+,:=/-]+', str(path)) or '..' in path.parts or str(path) == '/':
        raise ValueError('absolute path without spaces, shell syntax or .. required: ' + str(path))
    return path


def check_target(path, home):
    if path.is_symlink() or not path.resolve().is_relative_to(home.resolve()):
        raise ValueError('symlink or path escaping Termux home: ' + str(path))
    if path.exists() and not path.is_file():
        raise ValueError('entry is not a regular file: ' + str(path))


def target(report, row):
    base = Path(report[row.get('scope', 'home')])
    path = base / row['name']
    check_target(path, base)
    return path


def plan(home, prefix, rootfs, companion=None):
    home, prefix, rootfs = map(safe_path, (home, prefix, rootfs))
    if not home.is_dir() or home.is_symlink():
        raise ValueError('existing non-symlink Termux home required')
    if home.stat().st_uid != os.getuid():
        raise ValueError('run this tool as the target Termux user, not through su')
    values = {}
    for target, source in ENTRIES.items():
        text = (ROOT / 'reference/termux' / source).read_text()
        text = '#!' + str(prefix / 'bin/bash') + '\n' + text.split('\n', 1)[1]
        subprocess.run(['bash', '-n'], input=text, text=True, check=True, capture_output=True)
        values[target] = text.encode()
    values['debian-gpu.conf'] = (
        '# Generated by configure-termux.py; no credentials.\n'
        'DEBIAN_ROOTFS=' + shlex.quote(str(rootfs)) + '\n'
        'DEBIAN_TERMUX_PREFIX=' + shlex.quote(str(prefix)) + '\n'
        'DEBIAN_ADB_SERVER_PORT=' + str(20000 + os.getuid() % 40000) + '\n').encode()
    files = [('home', name, data) for name, data in values.items()]
    if companion:
        manifest = json.loads((companion / 'SHA256.json').read_text())
        for name in ('loader.apk', 'termux-x11', 'termux-x11-preference'):
            data = (companion / name).read_bytes()
            if digest(data) != manifest[name]:
                raise ValueError('companion checksum mismatch: ' + name)
            if name != 'loader.apk':
                data = data.replace(b'/data/data/com.termux/files/usr', str(prefix).encode())
            files.append(('prefix', 'libexec/termux-x11/loader.apk' if name == 'loader.apk' else 'bin/' + name, data))
    rows = []
    for scope, name, data in files:
        path = (home if scope == 'home' else prefix) / name
        check_target(path, home if scope == 'home' else prefix)
        before = path.read_bytes() if path.exists() else None
        if before == data:
            continue
        rows.append(dict(scope=scope, name=name, before=None if before is None else digest(before),
                         after=digest(data), data=base64.b64encode(data).decode()))
    return dict(format=1, home=str(home), prefix=str(prefix), rootfs=str(rootfs), state='planned',
                missing_dependencies=[name for name in REQUIRED if not os.access(prefix / 'bin' / name, os.X_OK)],
                entries=rows)


def atomic(path, data, mode, metadata=None):
    path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    fd, temporary = tempfile.mkstemp(prefix='.' + path.name + '.', dir=path.parent)
    try:
        with os.fdopen(fd, 'wb') as target:
            target.write(data)
            target.flush()
            os.fsync(target.fileno())
        if metadata:
            os.chown(temporary, metadata['uid'], metadata['gid'])
            for name, value in metadata['xattrs'].items():
                decoded = base64.b64decode(value)
                if name not in os.listxattr(temporary) or os.getxattr(temporary, name) != decoded:
                    os.setxattr(temporary, name, decoded)
        os.chmod(temporary, mode)
        os.replace(temporary, path)
    finally:
        if os.path.lexists(temporary):
            os.unlink(temporary)


def save(backup, report):
    atomic(backup / 'receipt.json', (json.dumps(report, indent=2) + '\n').encode(), 0o600)


def apply(report, backup):
    if report['missing_dependencies']:
        raise ValueError('missing Termux packages; run bootstrap-termux.sh: ' + ', '.join(report['missing_dependencies']))
    home = Path(report['home'])
    backup = backup.absolute()
    # A backup must not overlap an entry or one of its parent directories.
    for row in report['entries']:
        path = target(report, row)
        if backup == path or backup in path.parents or path in backup.parents:
            raise ValueError('backup overlaps managed entries')
    backup.mkdir(parents=True, exist_ok=False, mode=0o700)
    backup.chmod(0o700)
    for i, row in enumerate(report['entries']):
        path = target(report, row)
        actual = digest(path.read_bytes()) if path.exists() else None
        if actual != row['before']:
            raise ValueError('entry changed since planning: ' + str(path))
        if path.exists():
            info = path.stat()
            row['metadata'] = dict(mode=stat.S_IMODE(info.st_mode), uid=info.st_uid, gid=info.st_gid,
                                   xattrs={n: base64.b64encode(os.getxattr(path, n)).decode() for n in os.listxattr(path)})
            row['backup'] = f'entry-{i}'
            atomic(backup / row['backup'], path.read_bytes(), 0o600)
    report['state'] = 'prepared'
    save(backup, report)
    try:
        for row in report['entries']:
            path = target(report, row)
            if (digest(path.read_bytes()) if path.exists() else None) != row['before']:
                raise ValueError('entry changed during deployment: ' + str(path))
            atomic(path, base64.b64decode(row['data']),
                   0o400 if path.suffix == '.apk' else 0o600 if path.suffix == '.conf' else 0o700,
                   row.get('metadata'))
        report['state'] = 'configured'
        save(backup, report)
    except Exception:
        restore(backup, report, execute=True)
        raise


def restore(backup, report, execute=False):
    home = Path(report['home'])
    if home.stat().st_uid != os.getuid():
        raise ValueError('restore as the target Termux user')
    for row in report['entries']:
        path = target(report, row)
        actual = digest(path.read_bytes()) if path.exists() else None
        if actual not in (row['before'], row['after']):
            raise ValueError('user changed entry; restore refused: ' + str(path))
        if row['before'] is not None:
            saved = backup / row['backup']
            if not saved.resolve().is_relative_to(backup.resolve()) or digest(saved.read_bytes()) != row['before']:
                raise ValueError('backup corrupted: ' + str(saved))
    if execute:
        for row in report['entries']:
            path = target(report, row)
            if row['before'] is None:
                path.unlink(missing_ok=True)
            else:
                atomic(path, (backup / row['backup']).read_bytes(), row['metadata']['mode'], row['metadata'])
        report['state'] = 'restored'
        save(backup, report)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--home', type=Path, default=Path.home())
    parser.add_argument('--prefix', type=Path, default=Path(os.environ.get('PREFIX', '/data/data/com.termux/files/usr')))
    parser.add_argument('--rootfs', type=Path, default=Path('/data/linux/debian'))
    parser.add_argument('--companion', type=Path,
                        default=(ROOT / 'artifacts/x11-companion') if (ROOT / 'artifacts/x11-companion').is_dir() else None)
    parser.add_argument('--apply', action='store_true')
    parser.add_argument('--backup', type=Path)
    parser.add_argument('--restore', type=Path)
    args = parser.parse_args()
    if args.restore:
        report = json.loads((args.restore / 'receipt.json').read_text())
        restore(args.restore, report, args.apply)
    else:
        report = plan(args.home, args.prefix, args.rootfs, args.companion)
        if args.apply:
            if not args.backup:
                parser.error('--apply requires a new --backup directory')
            apply(report, args.backup)
    # No file contents in normal output.
    print(json.dumps({**report, 'entries': [{k: v for k, v in r.items() if k not in ('data', 'metadata')}
                                          for r in report['entries']]}, indent=2))


if __name__ == '__main__':
    main()
